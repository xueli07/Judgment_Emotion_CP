# Individual-Level PPC Correlation Scatter Plots
# Description: Validates model fit by plotting observed empirical data against 
#              model-predicted metrics (Accuracy & Correct RT) at the individual 
#              subject level. Generates 1x4 facetted scatter plots with linear 
#              fits, reference lines, and goodness-of-fit statistics (r, p, RMSE).
# ==============================================================================

rm(list = ls())

library(tidyverse)
library(ggplot2)
library(scales)
library(conflicted)

# Resolve namespace conflicts in favor of dplyr
conflicts_prefer(dplyr::filter)
conflicts_prefer(dplyr::select)

# --- 1. Directory Configuration & Data Loading ---
script_arg <- grep("^--file=", commandArgs(trailingOnly = FALSE), value = TRUE)
script_dir <- if (length(script_arg)) dirname(normalizePath(sub("^--file=", "", script_arg[1]))) else normalizePath(getwd())
package_root <- normalizePath(file.path(script_dir, "..", ".."))
base_dir <- file.path(package_root, "reference_outputs", "hddm", "result", "formal_model", "M4_v_judgment_x_pair")
setwd(base_dir)

# Load the aggregated master dataset generated by the Python PPC pipeline
csv_file <- "Master_PPC_Simulations_Aggregated.csv"
if(!file.exists(csv_file)) {
  stop("[ERROR] CSV data file not found. Please verify the file path.")
}

data_main <- read_csv(csv_file, show_col_types = FALSE)

# Harmonize subject identifier naming conventions
if ("subj_idx" %in% names(data_main)) {
  data_main <- data_main %>% rename(subject_id = subj_idx)
}

# Factorize and format labels for clean facet grid titles
data_main <- data_main %>%
  mutate(
    subject_id = as.factor(subject_id),
    judgment_condition = factor(judgment_condition, levels = c("categorical", "continuous")),
    pair_type = factor(pair_type, levels = c("between", "within")),
    # Create a composite condition label for facet headers (e.g., "Categorical | Between")
    condition_label = paste(str_to_title(judgment_condition), str_to_title(pair_type), sep = " | ")
  )

# --- 2. Core Data Aggregation (Trial-Level to Subject-Level) ---
cat("[INFO] Aggregating observed and predicted values to the individual subject level...\n")

# Robust aggregation: Extends absolute observed RTs and strictly aligns correct trials
subject_data <- data_main %>%
  mutate(Observed_RT_abs = abs(Observed_RT)) %>%
  group_by(subject_id, judgment_condition, pair_type, condition_label) %>%
  summarise(
    # Accuracy Mappings
    Obs_Acc  = mean(Observed_Acc, na.rm = TRUE),
    Pred_Acc = mean(Simulated_Acc_Mean, na.rm = TRUE),
    
    # Correct RT Mappings (Observed filtered for success; Pred uses dedicated simulated metric)
    Obs_RT   = mean(Observed_RT_abs[Observed_Acc == 1], na.rm = TRUE),
    Pred_RT  = mean(Simulated_RT_Mean_Correct, na.rm = TRUE),
    
    .groups  = "drop"
  ) %>%
  drop_na() # Eliminate subjects with zero correct trials in a specific condition yielding NaN

# --- 3. Plotting Aesthetics Configuration ---
color_cat  <- "#F28E8E"   # Categorical group palette
color_cont <- "#7FB3FF"   # Continuous group palette

#' Publication-Ready Scatter Plot Theme
#'
#' @param base_size The base font size for the plot.
#' @return A ggplot2 theme object optimized for facetted scatter plots.
theme_scatter <- function(base_size = 12) {
  theme_bw(base_size = 16) +
    theme(
      panel.grid.major = element_line(color = "gray90", linetype = "dashed"),
      panel.grid.minor = element_blank(),
      strip.background = element_rect(fill = "gray20", color = "black"),
      strip.text = element_text(color = "white", face = "bold", size = 14),
      axis.line = element_line(color = "black", linewidth = 1),
      axis.title = element_text(size = 18, face = "bold"),
      axis.title.y = element_text(margin = margin(r = 15)),
      axis.title.x = element_text(margin = margin(t = 15)),
      axis.text = element_text(size = 14, color = "black"),
      legend.position = "none" # Legend omitted as colors match facet headers
    )
}

# --- 4. Statistical Utility Functions ---

#' Calculate Goodness-of-Fit Statistics
#'
#' Computes Pearson correlation coefficients (r), associated p-values, and 
#' Root Mean Square Error (RMSE) between observed and predicted vectors.
#'
#' @param df Data frame containing the target columns.
#' @param obs_col String specifying the observed data column.
#' @param pred_col String specifying the predicted data column.
#' @return A data frame with formatted statistical annotation labels.
calculate_stats_label <- function(df, obs_col, pred_col) {
  df %>%
    group_by(condition_label) %>%
    summarise(
      r = cor(.data[[obs_col]], .data[[pred_col]]),
      p = cor.test(.data[[obs_col]], .data[[pred_col]])$p.value,
      rmse = sqrt(mean((.data[[obs_col]] - .data[[pred_col]])^2)),
      .groups = "drop"
    ) %>%
    mutate(
      p_text = ifelse(p < 0.001, "p < .001", sprintf("p = %.3f", p)),
      stat_label = sprintf("r = %.3f, %s\nRMSE = %.3f", r, p_text, rmse)
    )
}

# --- 5. Core Plotting Function ---

#' Create Validation Scatter Plot
#'
#' Generates a multi-panel scatter plot comparing empirical observations against 
#' model predictions, ensuring a perfect 1:1 aspect ratio with a 45-degree reference line.
#'
#' @param data Data frame containing the aggregated subject-level data.
#' @param obs_col Column name for empirical observations.
#' @param pred_col Column name for model predictions.
#' @param metric_name Human-readable metric name for titles (e.g., "Accuracy").
#' @param unit Optional measurement unit (e.g., "(s)" for seconds).
#' @return A ggplot2 object.
create_scatter_plot <- function(data, obs_col, pred_col, metric_name, unit = "") {
  
  # Establish global limits to ensure a perfectly square coordinate system
  min_val <- min(c(data[[obs_col]], data[[pred_col]]), na.rm = TRUE)
  max_val <- max(c(data[[obs_col]], data[[pred_col]]), na.rm = TRUE)
  padding <- (max_val - min_val) * 0.1
  lims <- c(min_val - padding, max_val + padding)
  
  # Generate statistical annotations
  stats_data <- calculate_stats_label(data, obs_col, pred_col)
  
  ggplot(data, aes(x = .data[[obs_col]], y = .data[[pred_col]], fill = judgment_condition)) +
    # 45-degree identity reference line (y = x)
    geom_abline(intercept = 0, slope = 1, color = "gray60", linetype = "dashed", linewidth = 1.2) +
    # Linear regression fit
    geom_smooth(aes(color = judgment_condition), method = "lm", se = FALSE, linewidth = 2, alpha = 0.8) +
    # Scatter points with distinct white borders for high-contrast aesthetic
    geom_point(shape = 21, color = "white", size = 4, stroke = 0.8, alpha = 0.85) +
    # Top-left statistical annotation text
    geom_text(data = stats_data, aes(x = -Inf, y = Inf, label = stat_label), 
              hjust = -0.1, vjust = 1.3, size = 4.5, fontface = "bold", color = "black", inherit.aes = FALSE) +
    # Color mappings
    scale_fill_manual(values = c("categorical" = color_cat, "continuous" = color_cont)) +
    scale_color_manual(values = c("categorical" = color_cat, "continuous" = color_cont)) +
    # Enforce square coordinate system mapping
    coord_fixed(ratio = 1, xlim = lims, ylim = lims) +
    # Render 1x4 facet grid
    facet_wrap(~ condition_label, nrow = 1) +
    labs(
      x = sprintf("Observed %s %s", metric_name, unit),
      y = sprintf("Predicted %s %s", metric_name, unit),
      title = sprintf("Individual Differences Fit Validation: %s", metric_name)
    ) +
    theme_scatter() +
    theme(plot.title = element_text(size = 20, face = "bold", hjust = 0.5, margin = margin(b = 20)))
}

# --- 6. Execution and Export ---

plots_dir <- "plots_ppc_scatter"
dir.create(plots_dir, showWarnings = FALSE)

cat("[INFO] Rendering Accuracy validation scatter plots...\n")
plot_acc <- create_scatter_plot(subject_data, "Obs_Acc", "Pred_Acc", "Accuracy")
ggsave(file.path(plots_dir, "PPC_Scatter_Accuracy.jpg"), plot_acc, width = 16, height = 5, dpi = 300)

cat("[INFO] Rendering Correct RT validation scatter plots...\n")
plot_rt <- create_scatter_plot(subject_data, "Obs_RT", "Pred_RT", "Correct RT", unit = "(s)")
ggsave(file.path(plots_dir, "PPC_Scatter_Correct_RT.jpg"), plot_rt, width = 16, height = 5, dpi = 300)

cat("\n[SUCCESS] Individual-level PPC correlation plots successfully exported to the target directory.\n")
